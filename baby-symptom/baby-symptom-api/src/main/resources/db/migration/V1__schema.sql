-- =========================================================
-- 寶寶症狀 3D 圖解：資料庫結構
-- 用 Flyway 管理，啟動時自動建立；之後要改結構請新增 V3__xxx.sql，不要改這個檔。
-- 寫法同時相容 H2 與 PostgreSQL。
-- =========================================================

-- 身體部位：code 要和 3D 模型裡的物件名稱一致（head、chest...）
CREATE TABLE body_part (
    code        VARCHAR(30)  PRIMARY KEY,
    name        VARCHAR(30)  NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0
);

-- 症狀主表
CREATE TABLE symptom (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)  NOT NULL UNIQUE,        -- 網址與程式用的代碼，例如 jaundice
    name                VARCHAR(50)  NOT NULL,               -- 顯示名稱
    category            VARCHAR(20)  NOT NULL DEFAULT 'GENERAL', -- 分類：一般症狀／早產兒常見問題
    severity            VARCHAR(20)  NOT NULL,               -- 嚴重程度
    summary             VARCHAR(500) NOT NULL,               -- 簡介
    when_to_see_doctor  VARCHAR(500) NOT NULL,               -- 什麼時候要就醫
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT', -- 內容狀態
    reviewed_by         VARCHAR(50),                         -- 醫療審閱者
    reviewed_at         DATE,                                -- 審閱日期
    created_at          TIMESTAMP    NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    updated_by          VARCHAR(50)  NOT NULL,
    version             BIGINT       NOT NULL DEFAULT 0,     -- 樂觀鎖：防止兩人同時編輯互相覆蓋
    CONSTRAINT ck_symptom_severity CHECK (severity IN ('EMERGENCY', 'SOON', 'HOME', 'FOLLOW')),
    CONSTRAINT ck_symptom_category CHECK (category IN ('GENERAL', 'PREEMIE')),
    CONSTRAINT ck_symptom_status   CHECK (status   IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

-- 症狀 ↔ 部位（多對多）
CREATE TABLE symptom_body_part (
    symptom_id  BIGINT       NOT NULL,
    part_code   VARCHAR(30)  NOT NULL,
    PRIMARY KEY (symptom_id, part_code),
    CONSTRAINT fk_sbp_symptom FOREIGN KEY (symptom_id) REFERENCES symptom(id) ON DELETE CASCADE,
    CONSTRAINT fk_sbp_part    FOREIGN KEY (part_code)  REFERENCES body_part(code)
);

-- 症狀的徵兆清單（有順序）
CREATE TABLE symptom_sign (
    symptom_id  BIGINT        NOT NULL,
    sort_order  INT           NOT NULL,
    content     VARCHAR(100)  NOT NULL,
    PRIMARY KEY (symptom_id, sort_order),
    CONSTRAINT fk_sign_symptom FOREIGN KEY (symptom_id) REFERENCES symptom(id) ON DELETE CASCADE
);

-- 稽核紀錄：誰、什麼時候、做了什麼（只新增、不修改）
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMP     NOT NULL,
    username      VARCHAR(50)   NOT NULL,
    action        VARCHAR(30)   NOT NULL,   -- CREATE / UPDATE / STATUS / DELETE / LOGIN_OK / LOGIN_FAIL
    target        VARCHAR(40),              -- 症狀代碼
    detail        VARCHAR(500),
    ip_address    VARCHAR(45)
);

CREATE INDEX ix_symptom_status   ON symptom(status);
CREATE INDEX ix_symptom_category ON symptom(category);
CREATE INDEX ix_audit_occurred   ON audit_log(occurred_at);
